"""Derives eval ground truth from eval/company_manifest.json.

  - upstream/downstream: computed from the tables each system reads and writes
  - duplicate/partial/related: declared in the manifest (clusters, partial pairs,
    per-PR labels)

Writes eval/cases.json, consumed by eval/run_eval.py and eval/prompt_lab.py:
    {branch: {pr_folder: {main_folder: [relation, ...]}}}

    python -m eval.build_cases
"""
import json
from pathlib import Path

HERE = Path(__file__).parent
MANIFEST = json.loads((HERE / "company_manifest.json").read_text())
SYSTEMS = MANIFEST["systems"]

# Relations that count as "should be surfaced"; "related" is excluded from scoring
# (neither a miss nor a false positive) because reasonable people could disagree.
POSITIVE = ("duplicate", "partial", "upstream", "downstream")
SIMILARITY = ("duplicate", "partial")


def cluster_of(system):
    for cluster in MANIFEST["duplicate_clusters"]:
        if system in cluster:
            return set(cluster) - {system}
    return set()


def partners_of(system):
    return {b for a, b in MANIFEST["partial"] if a == system} | {a for a, b in MANIFEST["partial"] if b == system}


def similarity_truth(system):
    """For code that re-implements `system`: which folders on main it duplicates."""
    return {"duplicate": sorted({system} | cluster_of(system)), "partial": sorted(partners_of(system))}


def dataflow(reads, writes, exclude):
    out = {}
    for name, s in SYSTEMS.items():
        if name == exclude:
            continue
        if set(reads) & set(s["writes"]):
            out.setdefault(name, []).append("upstream")
        if set(writes) & set(s["reads"]):
            out.setdefault(name, []).append("downstream")
    return out


def folder_truth(folder, spec):
    truth = dataflow(spec.get("reads", []), spec.get("writes", []), exclude=folder)
    for relation in ("duplicate", "partial", "related"):
        for other in spec.get(relation, []):
            if other != folder:
                truth.setdefault(other, []).append(relation)
    # Full duplicates of a cluster member duplicate the whole cluster.
    for other in list(truth):
        if "duplicate" in truth[other]:
            for mate in cluster_of(other) - {folder}:
                truth.setdefault(mate, [])
                if "duplicate" not in truth[mate]:
                    truth[mate].append("duplicate")
    return {k: sorted(set(v)) for k, v in sorted(truth.items())}


def pr_cases():
    return {
        branch: {folder: folder_truth(folder, spec) for folder, spec in pr["folders"].items()}
        for branch, pr in MANIFEST["prs"].items()
    }


def main():
    cases = pr_cases()
    out = {"_doc": "Generated by eval/build_cases.py from eval/company_manifest.json; do not edit by hand."}
    out.update(cases)
    (HERE / "cases.json").write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")
    n = sum(len(f) for f in cases.values())
    print(f"wrote {len(cases)} PRs / {n} PR folders to eval/cases.json")


if __name__ == "__main__":
    main()
